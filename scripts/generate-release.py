#!/usr/bin/env python3
"""Generate Release with pinned dist and one checked success-only archive clause.

The disposable stock generation removes only ci from allow-dirty. --check and
failed generation never write checkout files; default atomically writes only the
fully validated release.yml. No permissive stock-output fallback is allowed.
"""
from __future__ import annotations

import argparse
import ast
import hashlib
import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
from pathlib import Path

STOCK = "(needs.custom-archive-check.result == 'skipped' || needs.custom-archive-check.result == 'success')"
STRICT = "needs.custom-archive-check.result == 'success'"
WORKFLOW = Path(".github/workflows/release.yml")


class GenerationError(RuntimeError):
    pass


def stock_metadata(text: str) -> str:
    block = re.search(r"^\[workspace\.metadata\.dist\]\n(.*?)(?=^\[|\Z)", text, re.M | re.S)
    if not block:
        raise GenerationError("missing workspace dist metadata")
    entries = list(re.finditer(r"^allow-dirty\s*=\s*(\[[^\n]*\])[^\n]*\n?", block.group(1), re.M))
    if len(entries) != 1:
        raise GenerationError("expected one explicit ci-only comparison replacement")
    entry = entries[0]
    modes = ast.literal_eval(entry.group(1))
    if not isinstance(modes, list) or not all(isinstance(mode, str) for mode in modes) or modes.count("ci") != 1:
        raise GenerationError("allow-dirty must contain ci exactly once")
    remaining = [mode for mode in modes if mode != "ci"]
    replacement = "allow-dirty = " + json.dumps(remaining) + "\n" if remaining else ""
    start, end = block.start(1) + entry.start(), block.start(1) + entry.end()
    return text[:start] + replacement + text[end:]


def tighten(stock: bytes) -> bytes:
    expected = STOCK.encode()
    if stock.count(expected) != 1:
        raise GenerationError("expected exactly one stock archive-check host clause")
    host = re.search(rb"^  host:\n(.*?)(?=^  [\w-]+:|\Z)", stock, re.M | re.S)
    condition = re.search(rb"^    if: (.*)$", host.group(1), re.M) if host else None
    if not condition or expected not in condition.group(1):
        raise GenerationError("stock archive-check clause must be in host admission")
    # Permit exactly this one replacement, preserving every other generated byte.
    before, after = stock.split(expected)
    return before + STRICT.encode() + after


def generate(root: Path, dist: str) -> bytes:
    version = subprocess.run([dist, "--version"], cwd=root, capture_output=True, text=True)
    if version.returncode or version.stdout.strip() != "cargo-dist 0.32.0":
        raise GenerationError("requires actual cargo-dist 0.32.0")
    with tempfile.TemporaryDirectory(prefix="release-generation-") as temporary:
        directory = Path(temporary).resolve()
        if directory == root or root in directory.parents:
            raise GenerationError("disposable generation root must be outside workspace")
        workspace = directory / "source"
        shutil.copytree(root, workspace, symlinks=True,
                        ignore=shutil.ignore_patterns(".git", "target", "__pycache__"))
        manifest = workspace / "Cargo.toml"
        manifest.write_text(stock_metadata(manifest.read_text()))
        result = subprocess.run([dist, "generate", "--mode", "ci"], cwd=workspace,
                                capture_output=True, text=True)
        if result.returncode:
            raise GenerationError(f"dist generation failed ({result.returncode}): {result.stderr.strip()}")
        return tighten((workspace / WORKFLOW).read_bytes())


def hashes(root: Path) -> str:
    entries = {str(path.relative_to(root)): hashlib.sha256(path.read_bytes()).hexdigest()
               for path in sorted(root.rglob("*")) if path.is_file()}
    return hashlib.sha256(json.dumps(entries, sort_keys=True).encode()).hexdigest()


def self_test() -> None:
    script = Path(__file__).resolve()
    with tempfile.TemporaryDirectory(prefix="release-generator-self-test-") as temporary:
        root = Path(temporary) / "workspace"
        (root / WORKFLOW.parent).mkdir(parents=True)
        (root / "Cargo.toml").write_text('[workspace.metadata.dist]\nallow-dirty = ["ci"]\n')
        (root / "unchanged.txt").write_bytes(b"preserve all other source bytes\n")
        base = b"# stock fixture\njobs:\n  host:\n    if: ${{ always() && " + STOCK.encode() + b" }}\n  announce:\n    runs-on: ubuntu-22.04\n"
        fixture = Path(temporary) / "stock.yml"
        fixture.write_bytes(base)
        generator = Path(temporary) / "dist-fixture"
        generator.write_text(
            f"#!{sys.executable}\nimport os,pathlib,sys\n"
            "case=os.environ.get('RELEASE_GENERATOR_CASE','correct')\n"
            "if sys.argv[1:]==['--version']:\n"
            " print('cargo-dist '+('0.31.0' if case=='wrong-version' else '0.32.0'));sys.exit(0)\n"
            "assert sys.argv[1:]==['generate','--mode','ci']\n"
            "assert 'allow-dirty' not in pathlib.Path('Cargo.toml').read_text()\n"
            "if case=='generator-error': sys.exit(9)\n"
            f"base=pathlib.Path({str(fixture)!r}).read_bytes()\n"
            f"clause={STOCK.encode()!r}\n"
            "if case=='missing': base=base.replace(clause,b'true')\n"
            "if case=='duplicate': base+=clause+b'\\n'\n"
            "if case=='changed': base=base.replace(b\"'skipped'\",b\"'cancelled'\")\n"
            "pathlib.Path('.github/workflows/release.yml').write_bytes(base)\n"
        )
        generator.chmod(0o755)
        argv = [sys.executable, str(script), "--workspace", str(root), "--dist", str(generator)]
        def invoke(case: str, check: bool, expected: int) -> None:
            before = hashes(root)
            env = dict(os.environ, RELEASE_GENERATOR_CASE=case)
            command = argv + (["--check"] if check else [])
            result = subprocess.run(command, env=env, capture_output=True, text=True)
            if result.returncode != expected:
                raise GenerationError(f"self-test {case} unexpected exit: {result.returncode}: {result.stderr}")
            after = hashes(root)
            if check or expected:
                if before != after:
                    raise GenerationError(f"self-test {case} mutated workspace")
            print(json.dumps({"case": case, "cwd": str(Path.cwd()), "argv": command,
                              "exit_code": result.returncode, "before_sha256": before,
                              "after_sha256": after, "stdout": result.stdout, "stderr": result.stderr}))
        invoke("correct", False, 0)
        final = (root / WORKFLOW).read_bytes()
        if final != base.replace(STOCK.encode(), STRICT.encode(), 1):
            raise GenerationError("self-test changed bytes outside the one authorized clause")
        invoke("correct", True, 0)
        for case in ("wrong-version", "generator-error", "missing", "duplicate", "changed"):
            invoke(case, False, 1)
            invoke(case, True, 1)
        (root / WORKFLOW).write_bytes(final + b"# manual drift\n")
        invoke("correct", True, 1)
        # Preserve a different allowed generation mode; only ci is removed.
        if stock_metadata('[workspace.metadata.dist]\nallow-dirty = ["ci", "msi"]\n') != '[workspace.metadata.dist]\nallow-dirty = ["msi"]\n':
            raise GenerationError("self-test disabled unrelated generation checks")
    print("Release generator self-test passed: one-clause-only, version/error/shape refusal, reproducibility and no-mutation")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--self-test", action="store_true")
    parser.add_argument("--workspace", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--dist", default="dist", help="pinned dist executable (also supports scripted fixture proof)")
    args = parser.parse_args()
    try:
        if args.self_test:
            self_test()
            return 0
        root = args.workspace.resolve()
        dist = shutil.which(args.dist)
        if not dist:
            raise GenerationError("cargo-dist executable not found")
        final = generate(root, str(Path(dist).resolve()))
        output = root / WORKFLOW
        if args.check:
            if output.read_bytes() != final:
                raise GenerationError("release.yml differs from checked generated output; run scripts/generate-release.py")
            print("Release generation check passed: pinned dist + one strict archive host clause")
        else:
            pending = None
            try:
                with tempfile.NamedTemporaryFile(dir=output.parent, prefix=".release-", delete=False) as file:
                    pending = Path(file.name)
                    file.write(final)
                pending.chmod(0o644)
                os.replace(pending, output)
            finally:
                if pending is not None:
                    pending.unlink(missing_ok=True)
            print("Generated release.yml: pinned dist + one strict archive host clause")
        return 0
    except (GenerationError, OSError, ValueError, SyntaxError, shutil.Error) as error:
        print(f"Release generation failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
