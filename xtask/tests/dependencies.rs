#[test]
fn lockfile_git_source_canary_fails() {
    let policy = xtask::dependencies::parse_deny_toml(&valid_policy_toml())
        .expect("valid policy should parse");
    xtask::dependencies::validate_policy_shape(&policy).expect("shape ok");

    let lock = r#"
[[package]]
name = "evil"
version = "0.1.0"
source = "git+https://example.com/evil.git?rev=deadbeef"
"#;
    let error = xtask::dependencies::check_lockfile_sources(lock, &policy)
        .expect_err("git source canary must fail");
    assert!(
        error.to_string().contains("disallowed git source"),
        "unexpected error: {error:#}"
    );
}

