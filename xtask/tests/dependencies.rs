#[test]
fn gpl_only_license_canary_fails() {
    let allowed: BTreeSet<String> = ["MIT", "Apache-2.0"]
        .into_iter()
        .map(str::to_string)
        .collect();
    assert!(
        !xtask::dependencies::license_expression_allowed("GPL-3.0-only", &allowed),
        "GPL-only must conflict with dual MIT/Apache-2.0 allowlist"
    );
}

#[test]
fn missing_deny_toml_canary_fails() {
    let dir = tempdir().expect("tempdir");
    fs::write(dir.path().join("Cargo.lock"), empty_lockfile()).expect("lock");
    fs::write(
        dir.path().join("Cargo.toml"),
        "[workspace]\nmembers = []\nresolver = \"2\"\n",
    )
    .expect("manifest");
    let error = xtask::dependencies::run(Some(dir.path())).expect_err("missing deny.toml");
    assert!(
        error.to_string().contains("deny.toml"),
        "unexpected error: {error:#}"
    );
}

