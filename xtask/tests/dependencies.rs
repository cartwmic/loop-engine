//! Fixture/canary coverage for the T030 dependency policy gate.
//!
//! Canaries are encoded in-process with temporary trees (no separate fixture
//! directory) so unauthorized paths stay untouched.

use std::collections::BTreeSet;
use std::fs;
use std::path::Path;
use std::process::Command;

use tempfile::tempdir;

fn write_minimal_workspace(root: &Path, deny_toml: &str, lock_text: &str) {
    fs::write(root.join("deny.toml"), deny_toml).expect("write deny.toml");
    fs::write(root.join("Cargo.lock"), lock_text).expect("write Cargo.lock");
    fs::write(
        root.join("Cargo.toml"),
        r#"[workspace]
members = ["crate-a"]
resolver = "2"

[workspace.package]
version = "0.1.0"
edition = "2024"
license = "MIT OR Apache-2.0"
"#,
    )
    .expect("write workspace Cargo.toml");
    let crate_dir = root.join("crate-a");
    fs::create_dir_all(crate_dir.join("src")).expect("mkdir crate-a");
    fs::write(
        crate_dir.join("Cargo.toml"),
        r#"[package]
name = "crate-a"
version.workspace = true
edition.workspace = true
license.workspace = true

[dependencies]
"#,
    )
    .expect("write crate Cargo.toml");
    fs::write(crate_dir.join("src/lib.rs"), "//! canary crate\n").expect("write lib.rs");
}

fn valid_policy_toml() -> String {
    r#"
[advisories]
yanked = "deny"
unmaintained = "workspace"
ignore = []

[licenses]
confidence-threshold = 0.8
unused-allowed-license = "allow"
allow = [
    "MIT",
    "Apache-2.0",
    "Apache-2.0 WITH LLVM-exception",
    "BSD-2-Clause",
    "BSD-3-Clause",
    "ISC",
    "0BSD",
    "Zlib",
    "Unlicense",
    "Unicode-3.0",
    "Unicode-DFS-2016",
    "CC0-1.0",
]
exceptions = []

[bans]
multiple-versions = "warn"
wildcards = "deny"

[sources]
unknown-registry = "deny"
unknown-git = "deny"
allow-registry = ["https://github.com/rust-lang/crates.io-index"]
allow-git = []
"#
    .to_string()
}

fn empty_lockfile() -> String {
    "# This file is automatically @generated by Cargo.\nversion = 4\n".to_string()
}

#[test]
fn dependencies_command_is_registered() {
    let output = Command::new(env!("CARGO_BIN_EXE_xtask"))
        .args(["help"])
        .output()
        .expect("xtask help should execute");
    assert!(output.status.success(), "help should succeed");
    let stdout = String::from_utf8_lossy(&output.stdout);
    assert!(
        stdout.contains("dependencies"),
        "help should list dependencies command: {stdout}"
    );
}

#[test]
fn dependencies_command_passes_for_current_repository() {
    let status = Command::new(env!("CARGO_BIN_EXE_xtask"))
        .arg("dependencies")
        .status()
        .expect("xtask binary should execute");
    assert!(
        status.success(),
        "dependencies command should pass for the current repository"
    );
}

#[test]
fn policy_shape_rejects_missing_required_license() {
    let mut policy = xtask::dependencies::parse_deny_toml(&valid_policy_toml())
        .expect("valid policy should parse");
    policy.allowed_licenses.remove("Unicode-3.0");
    let error = xtask::dependencies::validate_policy_shape(&policy)
        .expect_err("missing Unicode-3.0 must fail policy shape");
    assert!(
        error.to_string().contains("Unicode-3.0"),
        "unexpected error: {error:#}"
    );
}

